// One-off import of the real AKD Solar assets from _incoming/ into public/images/ + src/lib/projects.generated.ts.
// - Crops GPS-camera address stamps and phone watermarks (customer privacy).
// - Crops the Sector 14 office photo to the signboard (the door poster shows a politician).
// - Skips the subsidy-cheque photo (politicians on stage) — it is not used on the site.
// Usage: node scripts/import-assets.mjs
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const IN = "_incoming";
const OUT = "public/images";

/** fraction of the height to KEEP from the top (removes bottom stamps/watermarks) */
const KEEP_TOP = {
  "p07-1": 0.69, "p10-1": 0.66, "p13-1": 0.69, "p17-1": 0.69, "p18-1": 0.69, "p19-1": 0.67, "p20-1": 0.67, // GPS address stamps
  "p12-1": 0.965, "p12-2": 0.875, "p12-3": 0.875, "p16-1": 0.875, // phone watermark bar
  "p04-1": 0.93, "p04-2": 0.93, "p05-1": 0.95, "p06-1": 0.93, "p14-1": 0.93, "p15-1": 0.93, // small watermark / date stamp
};

async function save(src, dest, { keepTop = 1, region } = {}) {
  const meta = await sharp(src).metadata();
  let img = sharp(src).rotate();
  if (region) img = img.extract(region);
  else if (keepTop < 1) img = img.extract({ left: 0, top: 0, width: meta.width, height: Math.round(meta.height * keepTop) });
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const info = await img.resize({ width: 1600, withoutEnlargement: true }).jpeg({ quality: 80, mozjpeg: true }).toFile(dest);
  return { width: info.width, height: info.height };
}

const projects = JSON.parse(fs.readFileSync(path.join(IN, "projects.json"), "utf8"));
const dims = {};
for (const p of projects) {
  for (const src of p.images) {
    const id = path.basename(src, ".jpg");
    dims[src] = await save(path.join(IN, "projects", `${id}.jpg`), path.join(OUT, "projects", `${id}.jpg`), { keepTop: KEEP_TOP[id] ?? 1 });
  }
}
for (const f of ["ongrid-works-collage"]) {
  dims[`/images/projects/${f}.jpg`] = await save(path.join(IN, "projects", `${f}.jpg`), path.join(OUT, "projects", `${f}.jpg`));
}
for (let n = 1; n <= 6; n++) {
  dims[`/images/about/certificate-${n}.jpg`] = await save(path.join(IN, "about", `certificate-${n}.jpg`), path.join(OUT, "about", `certificate-${n}.jpg`));
}
dims["/images/about/honorary-doctorate.jpg"] = await save(path.join(IN, "about", "honorary-doctorate.jpg"), path.join(OUT, "about", "honorary-doctorate.jpg"));
// Signboard only: the lower part of this photo shows a poster with a politician
dims["/images/about/office-sonipat-sector14.jpg"] = await save(path.join(IN, "about", "office-sonipat-sector14.jpg"), path.join(OUT, "about", "office-sonipat-sector14.jpg"), {
  region: { left: 0, top: 0, width: 952, height: 330 },
});
dims["/images/brands/havells-residential-banner.jpg"] = await save(path.join(IN, "brands", "havells-residential-banner.jpg"), path.join(OUT, "brands", "havells-residential-banner.jpg"));

// Typed data for the site: captions never include customer names; "TODO" locations are dropped
const clean = (loc) => (!loc || /^TODO/i.test(loc) || /^new office$/i.test(loc) ? null : loc);
const data = projects.map((p) => ({
  id: p.id,
  capacity: p.capacity,
  category: p.category === "Commercial" ? "commercial" : "residential",
  type: p.type,
  location: clean(p.location),
  images: p.images.map((src) => ({ src, ...dims[src] })),
}));
const extras = Object.fromEntries(Object.entries(dims).filter(([k]) => !k.match(/\/projects\/p\d/)));
fs.writeFileSync(
  "src/lib/projects.generated.ts",
  `// Generated by scripts/import-assets.mjs from _incoming/projects.json — do not edit by hand.\n` +
    `export const projectsData = ${JSON.stringify(data, null, 2)} as const;\n\n` +
    `export const imageDims: Record<string, { width: number; height: number }> = ${JSON.stringify(extras, null, 2)};\n`,
);
console.log(`projects: ${data.length}, images: ${Object.keys(dims).length}`);
